"""Закон 5. Есть темы, на которых мрачная эстетика делает хуже.

Триггер — грубый, и это осознанно: лучше десять ложных срабатываний,
чем одно пропущенное. При срабатывании персона отключается полностью:
никакого образа, никакого стиля, обычная человеческая речь.
"""
from __future__ import annotations

import re

_RED = re.compile(
    r"(суицид|покончи[тл]|убить себя|не хочу жить|жить не хочу|свести счёты|"
    r"свести счеты|порезал|режу себя|селфхарм|self.?harm|"
    r"не ем (?:уже|несколько)|голодаю|вызываю рвоту|булими|анорекс|"
    r"передозир|избива|бьёт меня|бьет меня|насил)",
    re.IGNORECASE,
)

PLAIN_SYSTEM = (
    "Отвечай как обычный внимательный человек. Никакого образа, стилизации, "
    "метафор, мрачности и художественности — они здесь вредны. Коротко "
    "признай, что человеку тяжело, спроси, что происходит прямо сейчас, "
    "и мягко предложи поговорить с живым специалистом или человеком, "
    "которому он доверяет. Не перечисляй способы навредить себе и не "
    "предлагай физических приёмов вроде льда или боли. Не паникуй, "
    "не морализируй, будь тёплым и прямым."
)


def is_red_line(text: str) -> bool:
    return bool(_RED.search(text or ""))
